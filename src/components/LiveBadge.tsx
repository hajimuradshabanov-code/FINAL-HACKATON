import { useDataMode, useTelemetrySelect } from '../hooks/useTelemetry'
import { isSimulation } from '../data/createSource'

/** "Live" is only claimed for measured data; generated telemetry is labelled as a simulation. */
export function LiveBadge() {
  const conn = useTelemetrySelect((s) => s.connection)
  const simulation = isSimulation(useDataMode())
  const lost = conn === 'lost'
  const connecting = conn === 'connecting'
  if (simulation && !lost && !connecting)
    return (
      <span role="status" className="label inline-flex items-center gap-2 rounded-full px-2.5 py-1" style={{ border: '1px dashed var(--sim)', color: 'var(--sim)', background: 'rgba(201,168,255,.1)' }} title="Values are generated by the training simulator, not measured">
        <span className="inline-block h-[7px] w-[7px] rounded-full" style={{ background: 'var(--sim)' }} />
        Simulation
      </span>
    )
  return (
    <span
      role="status"
      aria-live="polite"
      data-status={lost ? 'critical' : 'normal'}
      className="label inline-flex items-center gap-2 rounded-full px-2.5 py-1"
      style={{ border: '1px solid rgba(255,75,62,.7)', color: 'var(--ink)', background: 'rgba(255,75,62,.08)' }}
    >
      <span
        className={`inline-block h-[7px] w-[7px] rounded-full ${lost ? 'blink' : connecting ? '' : 'pulse-dot'}`}
        style={{ background: connecting ? 'var(--taupe)' : 'var(--s)' }}
      />
      {lost ? 'Signal lost' : connecting ? 'Linking' : 'Live'}
    </span>
  )
}
