/**
 * Downloads the Inspiration4 clinical blood panels from NASA OSDR and writes them into
 * src/science/osdrData.ts, so the analysis in src/science/osdr.ts runs on the real published values
 * (offline, in the browser and in tests). Run with `npm run fetch:osdr`.
 *
 *  - OSD-569 / LSDS-7  Complete Blood Count (CBC), Quest Diagnostics
 *  - OSD-575 / LSDS-8  Comprehensive Metabolic Panel (CMP), Quest Diagnostics
 *
 * 4 crew (C001–C004), 7 draws: L-92, L-44, L-3 (pre-flight), R+1, R+45, R+82, R+194 (post-flight).
 * Rows are kept exactly as published; only "(FEMALE)" suffixes are folded into the analyte name and
 * the sex column records the reference range used.
 */
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'

const FILES = [
  { study: 'OSD-569', panel: 'CBC', file: 'LSDS-7_Complete_Blood_Count_CBC.upload_SUBMITTED.csv' },
  { study: 'OSD-575', panel: 'CMP', file: 'LSDS-8_Comprehensive_Metabolic_Panel_CMP.upload_SUBMITTED.csv' },
] as const

type Row = [analyte: string, value: number | null, lo: number | null, hi: number | null, unit: string, subject: string, sex: string, timepoint: string]

const num = (s: string) => (/^-?\d+(\.\d+)?$/.test(s.trim()) ? Number(s) : null)

async function main() {
  const panels: { study: string; panel: string; file: string; url: string; sha256: string; rows: Row[] }[] = []
  for (const f of FILES) {
    const url = `https://osdr.nasa.gov/geode-py/ws/studies/${f.study}/download?source=datamanager&file=${f.file}`
    const r = await fetch(url)
    if (!r.ok) throw new Error(`${r.status} ${url}`)
    const text = await r.text()
    const [header, ...lines] = text.trim().split(/\r?\n/)
    const cols = header.split(',')
    if (cols[0] !== 'ANALYTE' || cols.length !== 9) throw new Error(`unexpected header in ${f.file}: ${header}`)
    const rows: Row[] = lines.map((l) => {
      const c = l.split(',')
      return [c[0].replace(/\s*\(FEMALE\)$/, ''), num(c[1]), num(c[2]), num(c[3]), c[4], c[6], c[7], c[8]]
    })
    panels.push({ ...f, url, sha256: createHash('sha256').update(text).digest('hex'), rows })
    console.log(`${f.study} ${f.panel}: ${rows.length} rows`)
  }
  const out = `// GENERATED by scripts/fetch-osdr.ts on ${new Date().toISOString().slice(0, 10)} — do not edit by hand.
// Source: NASA Open Science Data Repository (osdr.nasa.gov), Inspiration4 crew clinical panels.
// Row: [analyte, value, refLow, refHigh, unit, subject, sex, timepoint]; null = not reported.

export type OsdrRow = readonly [string, number | null, number | null, number | null, string, string, string, string]

export interface OsdrPanel {
  study: string
  panel: 'CBC' | 'CMP'
  file: string
  url: string
  sha256: string
  rows: readonly OsdrRow[]
}

export const OSDR_PANELS: readonly OsdrPanel[] = ${JSON.stringify(panels.map(({ rows, ...meta }) => ({ ...meta, rows })), null, 0).replace(/\],\[/g, '],\n[')}
`
  writeFileSync(new URL('../src/science/osdrData.ts', import.meta.url), out)
  console.log('wrote src/science/osdrData.ts')
}

void main()
